import math
import random
from functools import lru_cache
from itertools import product

length = 6
prediction_error = 0.0
budgets = [4, 16]
strengths = [0.0, 2.0]
n_runs = 400
mask_samples = 30000
time_steps = 12
stop_time = 0.02
seed = 7

assert isinstance(length, int) and 2 <= length <= 10
assert 0 <= prediction_error <= 1
assert all(isinstance(n, int) and n > 0 for n in budgets)
assert strengths and all(sigma >= 0 for sigma in strengths)
assert isinstance(n_runs, int) and n_runs > 0
assert isinstance(mask_samples, int) and mask_samples > 0
assert isinstance(time_steps, int) and time_steps > 0
assert 0 < stop_time < 1
MASK = -1

# 1. Only model whether a position is still MASK, without predicting a token.
# alpha(t)=1-t. Closed-form reveal is (t-s)/t; frozen hazard gives 1-exp(-(t-s)/t).
rng = random.Random(seed)
closed = [True] * mask_samples
frozen = [True] * mask_samples
print("1. Time approximation (stop before the endpoint)")
print(" time  target_MASK  closed_form  frozen_rate")
for n in range(time_steps):
    t = 1 - (1 - stop_time) * n / time_steps
    s = 1 - (1 - stop_time) * (n + 1) / time_steps
    w = (t - s) / t
    frozen_w = -math.expm1(-(t - s) / t)
    for i in range(mask_samples):
        u = rng.random()  # couple the two reveal coins for comparison
        if closed[i] and u < w:
            closed[i] = False
        if frozen[i] and u < frozen_w:
            frozen[i] = False
    print(f"{s:5.2f}  {s:11.4f}  {sum(closed)/mask_samples:11.4f}  {sum(frozen)/mask_samples:11.4f}")


def probabilities(t, s, sigma):
    alpha_t, alpha_s = 1 - t, 1 - s
    r = -math.expm1(-sigma * (t - s))
    r = min(r, (1 - alpha_s) / alpha_t) if alpha_t > 0 else 0.0
    a = (alpha_s - alpha_t + r * alpha_t) / (1 - alpha_t)
    assert -1e-12 <= r <= 1 + 1e-12 and -1e-12 <= a <= 1 + 1e-12
    return r, a


# 2. Check a conditional snapshot, using the known original token.
t, s = 0.6, 0.4
sigma = max(strengths)
r, a = probabilities(t, s, sigma)
rng = random.Random(seed)
masked = 0
for _ in range(mask_samples):
    old_is_mask = rng.random() < t
    new_is_mask = rng.random() >= a if old_is_mask else rng.random() < r
    masked += new_is_mask
print("\n2. Known-clean finite-step remasking")
print(f"t={t}, s={s}, sigma={sigma}, remask r={r:.4f}, reveal a={a:.4f}")
print(f"visible mass: {(1-t)*(1-r)+t*a:.4f}; target={1-s:.4f}")
print(f"sampled MASK fraction={masked/mask_samples:.4f}; target={s:.4f}")

# 3. Generate full sequences. Every binary sequence has positive data mass,
# so the true posterior is defined even in a context generated by the sampler.
states = list(product((0, 1), repeat=length))
weights = [(.99 if sum(z) % 2 == 0 else .01) / 2 ** (length - 1) for z in states]


@lru_cache(maxsize=None)
def posterior(x):
    candidates = [(z, weight) for z, weight in zip(states, weights)
                  if all(a == MASK or a == b for a, b in zip(x, z))]
    mass = sum(weight for _, weight in candidates)
    assert mass > 0
    return tuple(sum(weight * z[ell] for z, weight in candidates) / mass
                 for ell in range(length))


def generate(steps, sigma, rng):
    x = [MASK] * length
    for n in range(steps, 0, -1):
        t, s = n / steps, (n - 1) / steps
        old = tuple(x)
        exact = posterior(old)  # exactly one full-context query per step
        prediction = [(1 - prediction_error) * p + prediction_error * .5 for p in exact]
        r, a = probabilities(t, s, sigma)
        for ell in range(length):
            if old[ell] != MASK:
                if rng.random() < r:
                    x[ell] = MASK
            elif rng.random() < a:
                x[ell] = int(rng.random() < prediction[ell])
    assert MASK not in x
    return tuple(x)


print("\n3. Finite-step generation; target even-parity probability=0.990")
print(f"Synthetic prediction error={prediction_error}; not a trained neural model.")
print(" queries  sigma  sampled_even")
for steps in budgets:
    for sigma in strengths:
        rng = random.Random(seed)
        even = sum(sum(generate(steps, sigma, rng)) % 2 == 0 for _ in range(n_runs))
        print(f"{steps:8d}  {sigma:5.1f}  {even/n_runs:12.3f}")
print("More remasking does not by itself guarantee a better finite-step distribution.")
